/** Translate supported interface labels without changing stored values. */
export function useTranslation() {
  const language = usePreferences((state) => state.language)
  return (text: string) => {
    if (language === 'en') return text
    if (language === 'fr' || language === 'es')
      return messages[text]?.[language === 'fr' ? 0 : 1] ?? text
    return additionalMessages[text]?.[{ ne: 0, ja: 1, ar: 2 }[language]] ?? text
  }
}
